    public AtelierView( Var<AtelierViewModel> vm, AtelierSheet sheet ) {
        this.vm    = vm;
        this.sheet = sheet;

        looms          = vm.zoomTo(AtelierViewModel::looms,          AtelierViewModel::withLooms);
        search         = vm.zoomTo(AtelierViewModel::search,         AtelierViewModel::withSearch);
        materialFilter = vm.zoomTo(AtelierViewModel::materialFilter, AtelierViewModel::withMaterialFilter);
        selectedRef    = vm.zoomTo(AtelierViewModel::selectedRef,    AtelierViewModel::withSelectedRef);
        journal        = vm.zoomTo(AtelierViewModel::journal,        AtelierViewModel::withJournal);
        status         = vm.zoomTo(AtelierViewModel::status,         AtelierViewModel::withStatus);
        millAccount    = vm.zoomTo(AtelierViewModel::millAccount,    AtelierViewModel::withMillAccount);
        millSecret     = vm.zoomTo(AtelierViewModel::millSecret,     AtelierViewModel::withMillSecret);
        rushOnly       = vm.zoomTo(AtelierViewModel::rushOnly,       AtelierViewModel::withRushOnly);
        journalOpen    = vm.zoomTo(AtelierViewModel::journalOpen,    AtelierViewModel::withJournalOpen);
        loomsRunning   = vm.zoomTo(AtelierViewModel::loomsRunning,   AtelierViewModel::withLoomsRunning);
        editorTab      = vm.zoomTo(AtelierViewModel::editorTab,      AtelierViewModel::withEditorTab);

        // The two lenses onto computed projections. Neither is a stored field of
        // the model, so both re-derive whenever any of their several inputs
        // change — and both fold what the user did back into the book.
        book  = vm.zoomTo(AtelierViewModel::orderTable, AtelierViewModel::withOrderTable);
        order = vm.zoomTo(AtelierViewModel::selected,   AtelierViewModel::withSelected);

        client  = order.zoomTo(Order::client,  Order::withClient);
        due     = order.zoomTo(Order::due,     Order::withDue);
        notes   = order.zoomTo(Order::notes,   Order::withNotes);
        fibre   = order.zoomTo(Order::fibre,   Order::withFibre);
        weave   = order.zoomTo(Order::weave,   Order::withWeave);
        finish  = order.zoomTo(Order::finish,  Order::withFinish);
        stage   = order.zoomTo(Order::stage,   Order::withStage);
        metres  = order.zoomTo(Order::metres,  Order::withMetres);
        sett    = order.zoomTo(Order::sett,    Order::withSett);
        widthCm = order.zoomTo(Order::widthCm, Order::withWidthCm);
        rush    = order.zoomTo(Order::rush,    Order::withRush);

        // The materials tree, both ways. The shape is derived from the shelves, so a
        // shipment that draws a fibre down is a new tree value; and the selection is a
        // lens which reads the filter string as a path of ids and writes a path back as
        // a filter string, so the tree, the menu's radio items and the store-room chips
        // all drive the one field without knowing about each other.
        materials        = vm.viewAs(MaterialNode.class, m -> MaterialNode.of(m.store()));
        selectedMaterial = vm.zoomTo(
                                m -> MaterialNode.pathFor(m.materialFilter()),
                                (m, path) -> m.withMaterialFilter(MaterialNode.filterFor(path)));

        store         = vm.viewAs(Tuple.classTyped(Yarn.class), AtelierViewModel::store);
        headline      = vm.viewAsString(AtelierViewModel::headline);
        emptyText     = vm.viewAsString(AtelierViewModel::emptyBookText);
        hasSelection  = vm.viewAs(Boolean.class, AtelierViewModel::hasSelection);
        isFiltered    = vm.viewAs(Boolean.class, AtelierViewModel::isFiltered);
        millConnected = vm.viewAs(Boolean.class, AtelierViewModel::millConnected);
        workload      = vm.viewAsDouble(AtelierViewModel::workload);
        bookHeight    = vm.viewAsInt(AtelierViewModel::bookHeight);
        bookCount     = book.viewAsString(table -> table.getRowCount() == 1 ? "1 commission"
                                                 : table.getRowCount() + " commissions");
        bookIsEmpty   = book.viewAs(Boolean.class, table -> table.getRowCount() == 0);

        orderTitle = order.viewAsString(Order::title);
        clothLine  = order.viewAsString(Order::cloth);
        swatchSvg  = order.viewAsString(AtelierArt::swatchSvg);

        journalButtonText = journalOpen.viewAsString(  open -> open    ? "▾  Day book" : "▸  Day book" );
        loomsButtonText   = loomsRunning.viewAsString( running -> running ? "❙❙  Looms" : "▶  Looms" );
        millButtonText    = millConnected.viewAsString(on -> on ? "Reorder yarn" : "Sign in" );

        // Model → view for the one thing Swing owns rather than we: which row of
        // the table is highlighted. Deferred to the next EDT cycle because the
        // table's own rebinding is triggered by the very same model change and
        // may not have happened yet. Both read the model when they run rather
        // than closing over the value the event carried: two of these can be
        // queued at once, and a deferred write of an outdated value is one the
        // Swing selection would report straight back as a fresh model change.
        Viewable.cast(selectedRef).onChange(From.ALL, it -> UI.runLater(this::highlightSelectedRow));
        Viewable.cast(order).onChange(From.ALL, it ->
            UI.run(() -> writeDocket(it.currentValue().orElse(Order.none()))));
        Viewable.cast(journal).onChange(From.ALL, it ->
            UI.run(() -> writeJournal(it.currentValue().orElse(""))));

        // Everything is built inside the sheet's scope, so the typography rules
        // reach every component in the tree.
        UI.use(sheet, () ->
            of(this)
            .withLayout("fill, wrap 1, ins 0, gap 0, hidemode 3")
            .withPrefSize(1300, 880)
            .withMinSize(0, 0)
            // The single place the shape of the window enters the model, and it
            // hands the numbers straight over rather than deciding what they
            // mean: a flow grid never stretches a row, so the order book has to
            // be told how tall to want to be.
            .onResize( it -> vm.update(From.VIEW, m -> m.withViewSize(it.getWidth(), it.getHeight())) )
            .add(GROW_X, menuBar())
            .add(GROW_X.and("wmin 0"), header())
            .add(GROW_X.and("wmin 0"), toolStrip())
            .add(GROW.and(PUSH).and("wmin 0"), page())
            .add(GROW_X.and("wmin 0"), dayBookDrawer())
            .add(GROW_X.and("wmin 0"), statusBar())
        );

        UI.runLater(LOOM_PULSE_MILLIS, TimeUnit.MILLISECONDS, this::pulseLoomFloor);
    }

    // ════════════════════════════════════════════════════════════════════════
    //  Top chrome
