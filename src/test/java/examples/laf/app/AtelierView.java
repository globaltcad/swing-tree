    /**
     *  A right-aligned metres cell with a little air after it, so a quantity does
     *  not end up touching the date beside it. The one configurator is called in
     *  both modes: editing hands the cell straight back so the commit still
     *  converts to the column's own {@code Integer} type, and only the rendered
     *  form is decorated.
     */
    private static CellConf<JTable, Object> rightAligned( CellConf<JTable, Object> cell ) {
        if ( cell.isEditing() )
            return cell;
        boolean selected = cell.isSelected();
        String  text     = String.valueOf(cell.entry().orElse(""));
        return cell.updateView( view -> view
            .orGetUi( () -> label("") )
            .updateIf(JLabel.class, l -> {
                l.setText(text);
                l.setHorizontalAlignment(SwingConstants.RIGHT);
                l.setBorder(BorderFactory.createEmptyBorder(0, 0, 0, UI.scale(10)));
                // Wearing the selection colour is how a renderer tells the
                // look-and-feel to fill the row; saying so here is what keeps
                // these two columns in step with the five Swing renders itself.
                l.setBackground(selected ? UIManager.getColor("Table.selectionBackground") : null);
                return l;
            })
        );
    }

