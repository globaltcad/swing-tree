/**
 *  <h1>Flaxen — the order book of a small weaving atelier</h1>
 *
 *  A working desktop application, built with SwingTree and painted by the
 *  {@link examples.laf.LinenLookAndFeel}. It exists to answer a question a
 *  component gallery cannot: <em>what does this look-and-feel feel like when
 *  somebody is actually using it all day?</em> So there is a real order book to
 *  edit, real looms that make progress, a store room that runs down as cloth
 *  ships, and a day book that records what happened.
 *
 *  <h2>What it does</h2>
 *  <ul>
 *    <li>An <b>order book</b> of commissions in a {@code JTable} bound to an
 *        immutable {@link TableData} value. Cells are editable in place, and the
 *        view model decides what an edit is allowed to mean.</li>
 *    <li>An <b>editor</b> for the selected commission across three tabs — the
 *        commission itself, the cloth (with a woven swatch generated from the
 *        weave), and the printable delivery note.</li>
 *    <li>A <b>materials tree</b> and a <b>store room</b>, either of which
 *        filters the book; shelves run down when a commission ships and are
 *        restocked through the mill portal. The tree is a {@code UI.tree(..)}
 *        bound to a {@link MaterialNode} derived from those very shelves, so it
 *        relabels itself as they empty.</li>
 *    <li>A <b>loom floor</b> that really runs: switch it on and the looms make
 *        progress, advance their commissions from station to station, and stop
 *        when the work is done.</li>
 *    <li>A <b>day book</b> drawer recording every one of those events.</li>
 *  </ul>
 *
 *  <h2>Four SwingTree ideas it is built out of</h2>
 *  <ol>
 *    <li><b>One immutable root, reached through lenses.</b> There is no Swing
 *        state in this class and no {@code setText} anywhere in it. Every widget
 *        binds a lens into the single {@link AtelierViewModel}, and two of those
 *        lenses point at things the model <em>computes</em> rather than stores:
 *        the order book as a table value, and the one selected commission. See
 *        {@link AtelierViewModel#orderTable()} and
 *        {@link AtelierViewModel#selected()}. A third points at the store room
 *        <em>as a tree</em>, and its selection is a lens which reads a filter
 *        string as a node and writes a node back as a filter string.</li>
 *    <li><b>A table is a value, and so is a tree.</b>
 *        {@code UI.table(Var<TableData>)} is the entire binding for the order
 *        book — no {@code TableModel}, no listener, no refresh call. The
 *        materials tree is the same idea one dimension further up:
 *        {@code UI.tree(..)} over one immutable {@link MaterialNode}, with a rule
 *        per node type saying where its children live. See
 *        {@link #materialsTree()}.</li>
 *    <li><b>Pictures are values too.</b> The cloth swatch is SVG <i>text</i>
 *        generated by {@link AtelierArt} and handed to a component with
 *        {@code withStyle(svg, (text, it) -> it.image(img -> img.svg(text)))},
 *        so it is re-derived and re-rendered crisply whenever the weave
 *        changes.</li>
 *    <li><b>Convergence without state.</b> The page is a twelve-column
 *        {@code AUTO_SPAN} grid and the store room is a nested grid inside its
 *        card, so dragging the window from ultrawide to a tall strip rearranges
 *        everything and loses nothing — with no breakpoint field and no resize
 *        listener driving it.</li>
 *  </ol>
 *
 *  <h2>Working with a SwingTree-backed look-and-feel</h2>
 *  Linen paints through the same style engine the application does, and its
 *  layer of the cascade is resolved <em>after</em> the application's
 *  {@link AtelierSheet}. So this view asks the look-and-feel for the surfaces
 *  and the button roles it wants — {@code .group(LinenSurface.CARD)},
 *  {@code .group(LinenVariant.PRIMARY)} — rather than painting them itself, and
 *  the sheet is left to do what the LAF does not: typography. The two files say
 *  more about why.
 *
 *  @see examples.laf.LinenLookAndFeel
 *  @see AtelierViewModel
 */
