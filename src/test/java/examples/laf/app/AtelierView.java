    /**
     *  {@link JMenuBar} has no SwingTree factory of its own, so the bar itself is
     *  wrapped with {@code of(..)} while its contents are declared normally. The
     *  three radio items are worth a look: each one binds a boolean lens
     *  <em>into a string</em> — reading "is the filter this material?" and
     *  writing the material back — which is how a plain {@code Var<String>} ends
     *  up driving a radio group with no extra state to keep in step.
     */
    private UIForAnySwing<?, JMenuBar> menuBar() {
        Var<Boolean> allMaterials = materialFilter.zoomTo(f -> f.isEmpty(),      (f, on) -> on ? "" : f);
        Var<Boolean> plantOnly    = materialFilter.zoomTo(f -> isOrigin(f, Fibre.Origin.PLANT),
                                                          (f, on) -> on ? Fibre.Origin.PLANT.label() : "");
        Var<Boolean> animalOnly   = materialFilter.zoomTo(f -> isOrigin(f, Fibre.Origin.ANIMAL),
                                                          (f, on) -> on ? Fibre.Origin.ANIMAL.label() : "");
        ButtonGroup materials = new ButtonGroup();

        return of(new JMenuBar())
            .add(menu("File").peek( m -> m.setMnemonic(KeyEvent.VK_F) )
                .add(menuItem("New docket").peek( mi -> mi.setAccelerator(accelerator(KeyEvent.VK_N)) )
                     .onClick( it -> vm.update(AtelierViewModel::addOrder) ))
                .add(menuItem("Duplicate commission").peek( mi -> mi.setAccelerator(accelerator(KeyEvent.VK_D)) )
                     .onClick( it -> vm.update(AtelierViewModel::duplicateSelected) ))
                .add(separator())
                .add(menu("Export delivery note")
                    .add(menuItem("as PDF…").onClick( it -> exported("PDF") ))
                    .add(menuItem("as PNG…").onClick( it -> exported("PNG") ))
                    .add(menuItem("as SVG…").onClick( it -> exported("SVG") ))
                )
                .add(separator())
                .add(menuItem("Close the workshop").peek( mi -> mi.setAccelerator(accelerator(KeyEvent.VK_Q)) )
                     .onClick( it -> closeWindow() ))
            )
            .add(menu("Edit").peek( m -> m.setMnemonic(KeyEvent.VK_E) )
                .add(menuItem("Advance to the next station")
                     .onClick( it -> vm.update(AtelierViewModel::advanceSelected) ))
                .add(menuItem("Strike out of the book…").onClick( it -> confirmAndStrike() ))
                .add(separator())
                .add(menuItem("Clear all filters").onClick( it -> vm.update(AtelierViewModel::clearFilters) ))
            )
            .add(menu("View").peek( m -> m.setMnemonic(KeyEvent.VK_V) )
                .add(checkBoxMenuItem("Day book", journalOpen)
                     .peek( mi -> mi.setAccelerator(accelerator(KeyEvent.VK_J)) ))
                .add(checkBoxMenuItem("Rush jobs only", rushOnly))
                .add(checkBoxMenuItem("Run the looms", loomsRunning))
                .add(separator())
                .add(radioButtonMenuItem("All materials", allMaterials).peek(materials::add))
                .add(radioButtonMenuItem("Plant fibres",  plantOnly).peek(materials::add))
                .add(radioButtonMenuItem("Animal fibres", animalOnly).peek(materials::add))
            )
            .add(menu("Help").peek( m -> m.setMnemonic(KeyEvent.VK_H) )
                .add(menuItem("About Flaxen…").onClick( it -> UI.message(
                        "Flaxen — the order book of the Aspang weaving atelier.\n\n"
                      + "A SwingTree application, painted by the Linen look-and-feel."
                     ).titled("About Flaxen").showAsInfo() ))
            );
    }

