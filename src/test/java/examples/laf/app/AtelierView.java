    // ── The two hand-synchronised Swing selections ────────────────────────

    /**
     *  Captures the order book's {@link JTable} and wires its row selection to
     *  the model. SwingTree wraps no binding for a table's selection, so this is
     *  the one place in the view that adds a Swing listener by hand; the
     *  {@code syncingSelection} flag keeps the two directions from chasing each
     *  other.
     */
    private void captureBook( JTable table ) {
        this.bookTable = table;
        table.setRowHeight(UI.scale(26));
        table.setFillsViewportHeight(true);
        table.getTableHeader().setReorderingAllowed(false);
        // Shares rather than pixels: JTable hands out the card's width in
        // proportion to these, so the client name is the column that grows.
        widthOf(table, AtelierViewModel.COL_REF,     80);
        widthOf(table, AtelierViewModel.COL_CLIENT, 150);
        widthOf(table, AtelierViewModel.COL_FIBRE,   84);
        widthOf(table, AtelierViewModel.COL_METRES,  84);
        widthOf(table, AtelierViewModel.COL_DUE,     72);
        widthOf(table, AtelierViewModel.COL_STAGE,   88);
        // The book opens with a commission already chosen, and the highlight has
        // to say so; the subscription below only ever hears about *changes*.
        UI.runLater(this::highlightSelectedRow);
        table.getSelectionModel().addListSelectionListener( event -> {
            if ( event.getValueIsAdjusting() || syncingSelection )
                return;
            int row = table.getSelectedRow();
            if ( row < 0 )
                return;
            String ref = String.valueOf(table.getValueAt(row, refColumn(table)));
            vm.update(From.VIEW, m -> m.select(ref));
        });
    }

    private void highlightSelectedRow() {
        JTable table = this.bookTable;
        if ( table == null )
            return;
        String ref = selectedRef.get();
        syncingSelection = true;
        try {
            int column = refColumn(table);
            for ( int row = 0; row < table.getRowCount(); row++ )
                if ( ref.equals(String.valueOf(table.getValueAt(row, column))) ) {
                    table.setRowSelectionInterval(row, row);
                    return;
                }
            table.clearSelection();
        } finally {
            syncingSelection = false;
        }
    }

    private static void widthOf( JTable table, String columnName, int width ) {
        table.getColumnModel().getColumn(table.getColumnModel().getColumnIndex(columnName))
             .setPreferredWidth(UI.scale(width));
    }

    private static int refColumn( JTable table ) {
        return table.getColumnModel().getColumnIndex(AtelierViewModel.COL_REF);
    }

    /**
     *  Captures the delivery-note pane and the day book and feeds both by hand.
     *  <p>
     *  These two are a workaround rather than a design choice, and the only
     *  places in the view where a bound property would have been the natural
     *  answer. {@code withText(Val<String>)} sets the text with the document's
     *  listeners temporarily removed, which is how SwingTree breaks the feedback
     *  loop between a text component and its property — but a document kit that
     *  builds a <em>structured</em> view out of those very events cannot survive
     *  it. Bound that way, the {@code JEditorPane} holds the right 1.7&nbsp;kB of
     *  HTML, reports a preferred size of 23×16 and renders nothing at all, and
     *  the {@code JTextPane} runs every day-book line together on one line. Both
     *  happen under any look-and-feel, Linen or not; a plain {@code setText}, as
     *  here, works. Ordinary {@code JTextField}s and {@code JTextArea}s are
     *  unaffected and are bound normally everywhere else in this view.
     *
     *  @param pane the editor pane the docket tab was given
     */
    private void captureDocket( JEditorPane pane ) {
        this.docketPane = pane;
        pane.setContentType("text/html");
        pane.setEditable(false);
        writeDocket(vm.get().selected());
    }

    private void writeDocket( Order order ) {
        if ( docketPane != null )
            docketPane.setText(AtelierArt.docketHtml(order));
    }

    /** @see #captureDocket(JEditorPane) — the day book needs the same treatment. */
    private void captureJournal( JTextPane pane ) {
        this.journalPane = pane;
        pane.setEditable(false);
        writeJournal(vm.get().journal());
    }

    private void writeJournal( String lines ) {
        if ( journalPane != null )
            journalPane.setText(lines);
    }

    /**
     *  The store room as a tree, and the clearest single illustration in this app of
     *  what {@code UI.tree(..)} is for.
     *  <p>
     *  There is no {@code TreeModel} here, no {@code DefaultMutableTreeNode} graph to
     *  build and no selection listener to wire. There is one value —
     *  {@link MaterialNode}, derived from the shelves — and a rule per node type
     *  saying where that type keeps its children and how it is labelled. Selecting a
     *  node writes the filter; filtering elsewhere moves the selection.
     *  <p>
     *  Two things are worth watching while the app runs. Shipping a commission draws
     *  its fibre down, which rewrites the whole tree value, and yet the branches the
     *  user has open stay open — a bound tree identifies its nodes by
     *  {@link MaterialNode#id()}, not by their contents, so an edit cannot invalidate
     *  a path. And the bolt whose stock crosses the low-water mark relabels itself on
     *  the spot, because its label is a function of the value rather than a string
     *  somebody remembered to update.
     */
    private UIForAnySwing<?, ?> materialsTree() {
        return
            tree(MaterialNode.class, materials, conf -> conf
                .nodesOf(MaterialNode.StoreRoom.class, it -> it
                    .children(MaterialNode.StoreRoom::shelves)
                    .text(MaterialNode.StoreRoom::label)
                    .toolTip( room -> "Everything the atelier has to weave with" )
                )
                .nodesOf(MaterialNode.Shelf.class, it -> it
                    .children(MaterialNode.Shelf::bolts)
                    .text( shelf -> shelf.label() + "  ·  " + shelf.bolts().size() )
                    .toolTip( shelf -> "Show only " + shelf.label().toLowerCase(Locale.ROOT) + " fibres" )
                )
                .nodesOf(MaterialNode.Bolt.class, it -> it
                    .text( bolt -> bolt.isLow() ? bolt.label() + "  ·  running low" : bolt.label() )
                    .toolTip( bolt -> bolt.metresInStock() + " m on the shelf" )
                )
            )
            .withSelection(selectedMaterial)
            .withInitialExpansionDepth(2);
    }
